import puppeteer from "puppeteer-core";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await puppeteer.connect({ browserURL: "http://127.0.0.1:9223", defaultViewport: null });
const page = await browser.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
await page.setViewport({ width: 1600, height: 960, deviceScaleFactor: 1 });
await page.goto("https://galaga-redux.kindof-lame.workers.dev/?view=side", { waitUntil: "domcontentloaded", timeout: 60000 });
await page.waitForFunction("window.__galaga !== undefined", { timeout: 25000 });
await page.evaluate(() => window.__galaga.setInput("start1", true));
await sleep(150);
await page.evaluate(() => window.__galaga.setInput("start1", false));
await page.waitForFunction(() => window.__galaga.engine.enemies.filter((e) => e.state === "formation").length >= 24, { timeout: 40000 });
await sleep(300);
await page.screenshot({ path: "shots/live-proportions.png" });
console.log(JSON.stringify(await page.evaluate(() => ({ parked: window.__galaga.engine.enemies.filter((e) => e.state === "formation").length }))));
console.log("errors:", errs.length ? errs[0] : "(none)");
await page.close();
browser.disconnect();
