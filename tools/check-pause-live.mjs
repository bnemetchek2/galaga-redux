import { createHash } from "node:crypto";
import puppeteer from "puppeteer-core";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const hash = (b) => createHash("sha256").update(b).digest("hex").slice(0, 10);
const browser = await puppeteer.connect({ browserURL: "http://127.0.0.1:9223", defaultViewport: null });
const page = await browser.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
await page.setViewport({ width: 1600, height: 960 });
await page.goto("https://galaga-redux.kindof-lame.workers.dev/?view=side", { waitUntil: "domcontentloaded", timeout: 60000 });
await page.waitForFunction("window.__galaga !== undefined", { timeout: 25000 });
await page.evaluate(() => window.__galaga.setInput("start1", true));
await sleep(150);
await page.evaluate(() => window.__galaga.setInput("start1", false));
await sleep(4000);
await page.click("#pause-toggle");
await sleep(200);
const t0 = await page.evaluate(() => window.__galaga.engine.time);
const a = await (await page.$(".enh-canvas")).screenshot();
await sleep(1200);
const t1 = await page.evaluate(() => window.__galaga.engine.time);
const b = await (await page.$(".enh-canvas")).screenshot();
console.log("live paused:", await page.evaluate(() => document.body.classList.contains("is-paused")));
console.log("live time frozen:", t0 === t1);
console.log("live 3d frame frozen:", hash(a) === hash(b));
await page.keyboard.press("ArrowLeft");
await sleep(600);
console.log("live key resumes:", (await page.evaluate(() => window.__galaga.engine.time)) > t1);
console.log("errors:", errs.length ? errs[0] : "(none)");
await page.close();
browser.disconnect();
